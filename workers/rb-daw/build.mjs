// RB Studio (rb-daw) build: packs src/ into the two modules Cloudflare runs, index.js and assets.js.
//
//   node build.mjs                    write dist/ (index.js, assets.js, manifest.json from live.json)
//   node build.mjs --compare <dir>    build, then compare with a pulled Worker (python3 rb-tools/cfworker.py pull rb-daw <dir>).
//                                     Exit 1 if live differs from this source (someone edited it in the Cloudflare dashboard,
//                                     or this folder has changes that aren't deployed yet). The build hash is ignored.
//
// assets.js holds BUILD (a hash of everything below, used as the ?v= cache key), SHELL (src/shell.html, the page;
// index.js fills in {{BASE}}, {{CANONICAL}}, {{BUILD}}, {{THEME_LINK}}) and ASSETS (src/assets/*, in assets.json's order,
// served at /daw/assets/<name>). In src/assets/main.js, "__BUILD__" becomes BUILD (the worklet URLs).
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = (p) => readFileSync(join(here, "src", p), "utf8");
// JSON with every non-ASCII character escaped: how ASSETS has always been written. (SHELL is plain JSON.stringify.)
const json = (v) => JSON.stringify(v).replace(/[\u0080-\uffff]/g, (c) => "\\u" + c.charCodeAt(0).toString(16).padStart(4, "0"));

export function build() {
  const shell = src("shell.html");
  const order = JSON.parse(readFileSync(join(here, "assets.json"), "utf8"));
  const assets = {};
  for (const { name, type } of order) assets[name] = { type, body: src(join("assets", name)) };
  const build = createHash("sha256").update(shell + json(assets)).digest("hex").slice(0, 12);
  for (const a of Object.values(assets)) a.body = a.body.replaceAll("__BUILD__", build);
  const assetsJs = "// Generated by build.mjs from src/. Do not edit.\n" + `export const BUILD = "${build}";\n`
    + `export const SHELL = ${JSON.stringify(shell)};\n` + `export const ASSETS = ${json(assets)};\n`;
  return { build, assetsJs, indexJs: src("index.js") };
}

const { build: hash, assetsJs, indexJs } = build();
const i = process.argv.indexOf("--compare");
if (i > 0) {
  const dir = process.argv[i + 1];
  const live = readFileSync(join(dir, "assets.js"), "utf8"), liveIndex = readFileSync(join(dir, "index.js"), "utf8");
  const liveBuild = (live.match(/^export const BUILD = "([0-9a-f]+)";$/m) || [])[1];
  const same = live.replaceAll(liveBuild, "BUILD") === assetsJs.replaceAll(hash, "BUILD") && liveIndex === indexJs;
  console.log(same ? `rb-daw: live matches src/ (live BUILD ${liveBuild}, this build ${hash})` : "rb-daw: live DIFFERS from src/");
  process.exit(same ? 0 : 1);
}
const out = join(here, "dist");
existsSync(out) || mkdirSync(out);
writeFileSync(join(out, "assets.js"), assetsJs);
writeFileSync(join(out, "index.js"), indexJs);
writeFileSync(join(out, "package.json"), '{"type":"module"}\n'); // lets node import dist/ for local tests (not uploaded)
const live = JSON.parse(readFileSync(join(here, "live.json"), "utf8"));
writeFileSync(join(out, "manifest.json"), JSON.stringify({ script: live.script, entry: "index.js", version: live.version,
  parts: [{ name: "assets.js", type: "application/javascript+module" }, { name: "index.js", type: "application/javascript+module" }] }, null, 2) + "\n");
console.log(`rb-daw: built dist/ (BUILD ${hash})`);
